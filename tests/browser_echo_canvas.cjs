const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
  await page.locator('#echoState').waitFor({state:'visible',timeout:20000});
  await page.waitForFunction(() => document.querySelector('#echoState')?.textContent?.includes('Ready · local'),{timeout:180000});
  await page.locator('#echoId').fill('test-001');
  await page.locator('#echoKind').fill('registry');
  await page.locator('#echoText').fill('A-000 Genesis indexing smoke test');
  await page.locator('#echoRegister').click();
  await page.waitForFunction(()=>document.querySelector('#echoResult')?.textContent?.includes('"indexed": true'),{timeout:20000});
  await page.locator('#echoQuery').fill('{ entity(id: "test-001") { id kind label text } }');
  await page.locator('#echoRun').click();
  await page.waitForFunction(()=>document.querySelector('#echoWidgets article')?.textContent?.includes('test-001'),{timeout:20000});
  const actual=await page.locator('#echoWidgets article').innerText();
  if(!actual.includes('A-000'))throw Error('Widget missing indexed text: '+actual);
  await page.locator('#echoQuery').fill('{ entity(id: "test-001") { forbidden } }');
  await page.locator('#echoRun').click();
  await page.waitForFunction(()=>document.querySelector('#echoResult')?.textContent?.includes('unknown field'),{timeout:20000});
  if(errors.length)throw Error('Browser errors: '+errors.join(' | '));
  console.log('PASS: Pyodide Genesis A-000 -> query -> widget, including unknown-field rejection');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
